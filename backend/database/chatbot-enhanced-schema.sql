CREATE SEQUENCE chatbot_selection_seq START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE chatbot_profile_seq START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE chatbot_variant_seq START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE chatbot_context_seq START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE chatbot_metric_seq START WITH 1 INCREMENT BY 1 INCREMENT BY 1 NOCACHE NOCYCLE;
