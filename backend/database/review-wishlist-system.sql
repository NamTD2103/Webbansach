-- 7. PRICE CHANGE NOTIFICATIONS
CREATE TABLE PRICE_CHANGE_NOTIFICATIONS (
  NOTIFICATION_ID NUMBER PRIMARY KEY,
  WISHLIST_ID NUMBER NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  OLD_PRICE NUMBER(10,2),
  NEW_PRICE NUMBER(10,2),
  DISCOUNT_PERCENT NUMBER(5,2),
  STATUS VARCHAR2(20) DEFAULT 'PENDING',
  SENT_AT TIMESTAMP,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (WISHLIST_ID) REFERENCES USER_WISHLIST(WISHLIST_ID),
  FOREIGN KEY (PRODUCT_ID) REFERENCES SANPHAM(MASP)
);

-- 8. STOCK NOTIFICATIONS
CREATE TABLE STOCK_NOTIFICATIONS (
  NOTIFICATION_ID NUMBER PRIMARY KEY,
  WISHLIST_ID NUMBER NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  OLD_STOCK NUMBER,
  NEW_STOCK NUMBER,
  STATUS VARCHAR2(20) DEFAULT 'PENDING',
  SENT_AT TIMESTAMP,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (WISHLIST_ID) REFERENCES USER_WISHLIST(WISHLIST_ID),
  FOREIGN KEY (PRODUCT_ID) REFERENCES SANPHAM(MASP)
);

-- ============================================
-- SEQUENCES
-- ============================================

CREATE SEQUENCE SEQ_REVIEW_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_REVIEW_IMAGE_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_REVIEW_LIKE_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_REVIEW_REPORT_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_SUMMARY_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_PRICE_NOTIFICATION_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_STOCK_NOTIFICATION_ID START WITH 1 INCREMENT BY 1;

-- ============================================
-- INDEXES
-- ============================================

CREATE INDEX IDX_REVIEW_PRODUCT ON PRODUCT_REVIEWS(PRODUCT_ID);
CREATE INDEX IDX_REVIEW_USER ON PRODUCT_REVIEWS(USER_ID);
CREATE INDEX IDX_REVIEW_RATING ON PRODUCT_REVIEWS(RATING);
CREATE INDEX IDX_REVIEW_STATUS ON PRODUCT_REVIEWS(STATUS);
CREATE INDEX IDX_REVIEW_SENTIMENT ON PRODUCT_REVIEWS(SENTIMENT);
CREATE INDEX IDX_REVIEW_CREATED ON PRODUCT_REVIEWS(CREATED_AT);
CREATE INDEX IDX_REVIEW_HELPFUL ON PRODUCT_REVIEWS(HELPFUL_COUNT DESC);

CREATE INDEX IDX_REVIEW_IMAGE_REVIEW ON REVIEW_IMAGES(REVIEW_ID);
CREATE INDEX IDX_REVIEW_LIKE_REVIEW ON REVIEW_LIKES(REVIEW_ID);
CREATE INDEX IDX_REVIEW_LIKE_USER ON REVIEW_LIKES(USER_ID);
CREATE INDEX IDX_REVIEW_REPORT_REVIEW ON REVIEW_REPORTS(REVIEW_ID);
CREATE INDEX IDX_REVIEW_REPORT_STATUS ON REVIEW_REPORTS(STATUS);

CREATE INDEX IDX_SUMMARY_PRODUCT ON PRODUCT_REVIEW_SUMMARY(PRODUCT_ID);
CREATE INDEX IDX_PRICE_NOTIF_WISHLIST ON PRICE_CHANGE_NOTIFICATIONS(WISHLIST_ID);
CREATE INDEX IDX_STOCK_NOTIF_WISHLIST ON STOCK_NOTIFICATIONS(WISHLIST_ID);

-- ============================================
-- TRIGGERS (Optional - for audit)
-- ============================================

-- Update UPDATED_AT timestamp automatically
CREATE OR REPLACE TRIGGER TRG_REVIEW_UPDATE
BEFORE UPDATE ON PRODUCT_REVIEWS
FOR EACH ROW
BEGIN
  :NEW.UPDATED_AT := CURRENT_TIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER TRG_SUMMARY_UPDATE
BEFORE UPDATE ON PRODUCT_REVIEW_SUMMARY
FOR EACH ROW
BEGIN
  :NEW.LAST_UPDATED := CURRENT_TIMESTAMP;
END;
/

