-- ============================================
-- REVIEW & WISHLIST SYSTEM
-- ============================================

-- 1. PRODUCT REVIEWS TABLE
CREATE TABLE PRODUCT_REVIEWS (
  REVIEW_ID NUMBER PRIMARY KEY,
  PRODUCT_ID NUMBER NOT NULL,
  USER_ID NUMBER NOT NULL,
  RATING NUMBER(2,1) NOT NULL CHECK (RATING >= 1 AND RATING <= 5),
  TITLE VARCHAR2(255),
  CONTENT CLOB,
  VERIFIED_PURCHASE NUMBER(1) DEFAULT 0,
  HELPFUL_COUNT NUMBER DEFAULT 0,
  UNHELPFUL_COUNT NUMBER DEFAULT 0,
  STATUS VARCHAR2(20) DEFAULT 'PUBLISHED',
  SENTIMENT VARCHAR2(20),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (PRODUCT_ID) REFERENCES SANPHAM(MASP),
  FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

-- 2. REVIEW IMAGES TABLE
CREATE TABLE REVIEW_IMAGES (
  IMAGE_ID NUMBER PRIMARY KEY,
  REVIEW_ID NUMBER NOT NULL,
  IMAGE_URL VARCHAR2(500),
  DISPLAY_ORDER NUMBER,
  UPLOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (REVIEW_ID) REFERENCES PRODUCT_REVIEWS(REVIEW_ID) ON DELETE CASCADE
);

-- 3. REVIEW LIKES TABLE
CREATE TABLE REVIEW_LIKES (
  LIKE_ID NUMBER PRIMARY KEY,
  REVIEW_ID NUMBER NOT NULL,
  USER_ID NUMBER NOT NULL,
  LIKE_TYPE VARCHAR2(10) CHECK (LIKE_TYPE IN ('HELPFUL', 'UNHELPFUL')),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (REVIEW_ID, USER_ID, LIKE_TYPE),
  FOREIGN KEY (REVIEW_ID) REFERENCES PRODUCT_REVIEWS(REVIEW_ID) ON DELETE CASCADE,
  FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 4. REVIEW REPORTS TABLE
CREATE TABLE REVIEW_REPORTS (
  REPORT_ID NUMBER PRIMARY KEY,
  REVIEW_ID NUMBER NOT NULL,
  REPORTER_ID NUMBER NOT NULL,
  REASON VARCHAR2(255),
  DESCRIPTION CLOB,
  STATUS VARCHAR2(20) DEFAULT 'PENDING',
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  RESOLVED_AT TIMESTAMP,
  FOREIGN KEY (REVIEW_ID) REFERENCES PRODUCT_REVIEWS(REVIEW_ID) ON DELETE CASCADE,
  FOREIGN KEY (REPORTER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 5. PRODUCT REVIEW SUMMARY (Cached AI Insights)
CREATE TABLE PRODUCT_REVIEW_SUMMARY (
  SUMMARY_ID NUMBER PRIMARY KEY,
  PRODUCT_ID NUMBER NOT NULL UNIQUE,
  AVERAGE_RATING NUMBER(3,2),
  TOTAL_REVIEWS NUMBER,
  RATING_DISTRIBUTION CLOB,
  AI_SUMMARY CLOB,
  POSITIVE_PERCENT NUMBER(5,2),
  NEUTRAL_PERCENT NUMBER(5,2),
  NEGATIVE_PERCENT NUMBER(5,2),
  KEY_STRENGTHS CLOB,
  KEY_WEAKNESSES CLOB,
  LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (PRODUCT_ID) REFERENCES SANPHAM(MASP)
);

